/**
 * wp-theme-control (Node port) — pattern file builder + patterns scope.
 *
 * Exports published unsynced user-created `wp_block` posts into
 * patterns/<slug>.php with namespaced slugs and the upstream safety
 * properties (slug charset guard, collision refusal, runtime URL
 * rewriting).
 */

import fs from 'fs';
import os from 'os';
import path from 'path';
import {
	assertSafeSlug,
	createRun,
	die,
	finishRun,
	info,
	installFile,
	manifestAdd,
	wp,
	wpEval,
	CLEAR_PATTERN_CACHE_EVAL,
} from './context.js';
import { rewriteRuntimeUrls } from './runtime-urls.js';
import { runClean } from './clean.js';

export const UNSYNCED_PATTERN_IDS_ARGS = [
	'post',
	'list',
	'--post_type=wp_block',
	'--post_status=publish',
	'--meta_key=wp_pattern_sync_status',
	'--meta_value=unsynced',
	'--format=ids',
];

/**
 * Builds the full pattern PHP file content (upstream wpctl_build_pattern_file
 * + the WP Rig `Baked: yes` header, D7).
 *
 * The header is part of the staged file (not injected afterwards) so the
 * manifest sha256 matches the final committed content and `clean` verifies
 * without --force.
 *
 * @param {Object} opts               Pattern metadata + body.
 * @param {string} opts.title         Pattern title.
 * @param {string} opts.slug          Full namespaced slug (theme/slug).
 * @param {string} [opts.categories]  Comma-separated categories.
 * @param {string} [opts.description] Description.
 * @param {string} opts.inserter      'yes' | 'no'.
 * @param {string} opts.body          Block markup body.
 * @return {string} PHP file content.
 */
export function buildPatternFile( {
	title,
	slug,
	categories = '',
	description = '',
	inserter,
	body,
} ) {
	const sanitize = ( value = '' ) =>
		value.replace( /[\r\n\t]/g, ' ' ).replace( /\*\//g, '* /' );

	const lines = [
		'<?php',
		'/**',
		' * Baked: yes',
		` * Title: ${ sanitize( title ) }`,
		` * Slug: ${ sanitize( slug ) }`,
	];

	if ( categories ) {
		lines.push( ` * Categories: ${ sanitize( categories ) }` );
	}
	if ( description ) {
		lines.push( ` * Description: ${ sanitize( description ) }` );
	}
	lines.push( ` * Inserter: ${ inserter }`, ' */', '?>', body, '' );

	return lines.join( '\n' );
}

/**
 * Description used for managed runtime patterns generated from templates.
 *
 * @param {string} type wp_template | wp_template_part.
 * @param {string} slug Template slug.
 * @return {string} Description text.
 */
export function runtimePatternDescription( type, slug ) {
	return `Generated by wp-theme-control from ${ type } ${ slug }.`;
}

export function runtimePatternSlug( type, slug ) {
	if ( type === 'wp_template' ) {
		return `hidden-template-${ slug }`;
	}
	if ( type === 'wp_template_part' ) {
		return `hidden-template-part-${ slug }`;
	}
	die( `unsupported runtime pattern source type: ${ type }` );
}

/**
 * Detects whether an existing runtime pattern file is managed by this tool
 * (safe to replace on --force).
 *
 * @param {string} filePath Runtime pattern file path.
 * @param {string} type     wp_template | wp_template_part.
 * @param {string} slug     Template slug.
 * @return {boolean} True when the file is managed by wp-theme-control.
 */
export function runtimePatternIsManaged( filePath, type, slug ) {
	if ( ! fs.existsSync( filePath ) ) {
		return false;
	}
	const description = runtimePatternDescription( type, slug );
	return fs
		.readFileSync( filePath, 'utf8' )
		.includes( ` * Description: ${ description }` );
}

/**
 * Fetches published unsynced pattern post IDs.
 *
 * @param {Object} ctx Loaded context.
 * @return {string[]} Pattern post IDs.
 */
export function unsyncedPatternIds( ctx ) {
	return wp( ctx, UNSYNCED_PATTERN_IDS_ARGS, { capture: true } )
		.split( /\s+/ )
		.map( ( line ) => line.trim() )
		.filter( ( line ) => line && /^\d+$/.test( line ) );
}

/**
 * Runs the patterns scope.
 *
 * @param {Object} ctx Loaded context (with parsed args).
 */
export function runPatterns( ctx ) {
	const patternIds = unsyncedPatternIds( ctx );

	if ( patternIds.length === 0 ) {
		info( 'no published unsynced user-created patterns found' );
		return;
	}

	if ( ctx.dryRun ) {
		const inspectDir = fs.mkdtempSync(
			path.join( os.tmpdir(), 'wtc-patterns-' )
		);
		try {
			for ( const id of patternIds ) {
				const slug = wp(
					ctx,
					[ 'post', 'get', id, '--field=post_name' ],
					{ capture: true }
				).trim();
				assertSafeSlug( slug );
				const target = path.join(
					ctx.themeDir,
					'patterns',
					`${ slug }.php`
				);
				const sourcePath = path.join(
					inspectDir,
					`${ slug }.source.html`
				);
				const outputPath = path.join(
					inspectDir,
					`${ slug }.output.html`
				);
				const reportPath = path.join(
					inspectDir,
					`${ slug }.report.json`
				);
				fs.writeFileSync(
					sourcePath,
					wp( ctx, [ 'post', 'get', id, '--field=post_content' ], {
						capture: true,
					} )
				);
				rewriteRuntimeUrls( ctx, sourcePath, outputPath, reportPath );
				const runtimeCount = JSON.parse(
					fs.readFileSync( reportPath, 'utf8' )
				).total;
				const state = fs.existsSync( target ) ? 'collision' : 'new';
				info(
					`would write pattern ${ id } -> ${ target } (${ state }; ${ runtimeCount } runtime URL(s))`
				);
			}
		} finally {
			fs.rmSync( inspectDir, { recursive: true, force: true } );
		}
		return;
	}

	createRun( ctx, 'patterns' );

	for ( const id of patternIds ) {
		if ( ! /^\d+$/.test( id ) ) {
			die( `invalid pattern post ID: ${ id }` );
		}
		const slug = wp( ctx, [ 'post', 'get', id, '--field=post_name' ], {
			capture: true,
		} ).trim();
		const title = wp( ctx, [ 'post', 'get', id, '--field=post_title' ], {
			capture: true,
		} ).trim();
		const categories = wp(
			ctx,
			[
				'post',
				'term',
				'list',
				id,
				'wp_pattern_category',
				'--field=slug',
			],
			{ capture: true }
		)
			.split( '\n' )
			.map( ( line ) => line.trim() )
			.filter( Boolean )
			.join( ', ' );
		assertSafeSlug( slug );

		const target = path.join( ctx.themeDir, 'patterns', `${ slug }.php` );
		const sourcePath = path.join(
			ctx.runDir,
			'staging',
			`${ slug }.source.html`
		);
		const bodyPath = path.join(
			ctx.runDir,
			'staging',
			`${ slug }.body.html`
		);
		const reportPath = path.join(
			ctx.runDir,
			'staging',
			`${ slug }.report.json`
		);
		const stage = path.join( ctx.runDir, 'staging', `${ slug }.php` );

		if ( fs.existsSync( target ) && ! ctx.force ) {
			die(
				`pattern file already exists: ${ target } (rerun with --force to back it up and replace it)`
			);
		}

		fs.writeFileSync(
			sourcePath,
			wp( ctx, [ 'post', 'get', id, '--field=post_content' ], {
				capture: true,
			} )
		);
		rewriteRuntimeUrls( ctx, sourcePath, bodyPath, reportPath );
		const runtimeCount = JSON.parse(
			fs.readFileSync( reportPath, 'utf8' )
		).total;

		fs.writeFileSync(
			stage,
			buildPatternFile( {
				title,
				slug: `${ ctx.themeSlug }/${ slug }`,
				categories,
				inserter: 'yes',
				body: fs.readFileSync( bodyPath, 'utf8' ),
			} )
		);

		installFile( ctx, stage, target );
		manifestAdd( ctx, 'wp_block', id, slug, target );
		info(
			`exported pattern ${ id } -> ${ target } (${ runtimeCount } local URL(s) rewritten)`
		);
	}

	wpEval( ctx, CLEAR_PATTERN_CACHE_EVAL );
	wp( ctx, [ 'cache', 'flush' ], { capture: true } );
	finishRun( ctx );

	if ( ctx.clean ) {
		runClean( ctx, ctx.manifest );
	}
}
